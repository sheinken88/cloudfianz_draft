"""Prepare an indexable artifact, never overwrite preview or deploy anything."""
import json
from pathlib import Path
import shutil
from seo import ORIGIN

ROOT = Path(__file__).resolve().parent
SOURCE = ROOT / 'dist'
RELEASE = ROOT / 'release'
SITE = RELEASE / 'site'
routes = json.loads((ROOT / 'i18n/routes.json').read_text())
pages = ['index.html'] + [path.lstrip('/') + '/index.html' for group in routes.values() for path in group.values()]

# This directory is disposable build output, never the serving preview directory.
if RELEASE.exists():
    if not (RELEASE / '.generated').exists():
        raise SystemExit('Refusing to replace a release directory without the generated marker.')
    shutil.rmtree(RELEASE)
SITE.mkdir(parents=True)
(RELEASE / '.generated').write_text('Generated by package-release.py; do not edit.\n')
for relative in pages:
    source = (SOURCE / relative).read_text()
    if source.count('<meta name="robots" content="noindex, nofollow">') != 1:
        raise ValueError(f'Expected protected preview HTML: {relative}')
    source = source.replace('<meta name="robots" content="noindex, nofollow">',
                            '<meta name="robots" content="index, follow, max-image-preview:large">')
    source = source.replace('<meta name="site-environment" content="preview">',
                            '<meta name="site-environment" content="production">')
    destination = SITE / relative
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(source)
shutil.copytree(SOURCE / 'assets', SITE / 'assets')
for source in SOURCE.iterdir():
    if source.suffix in ('.css', '.js') and not source.name.startswith('review'):
        shutil.copy2(source, SITE / source.name)
shutil.copy2(SOURCE / 'sitemap.xml', SITE / 'sitemap.xml')
(SITE / 'robots.txt').write_text(f'User-agent: *\nAllow: /\n\nSitemap: {ORIGIN}/sitemap.xml\n')

# Optional Vercel configuration for the REAL-domain repository. This file is
# deliberately outside the active root configuration and is never auto-applied.
config = json.loads((ROOT.parent / 'vercel.json').read_text())
config['buildCommand'] = 'npm run build:release'
config['outputDirectory'] = 'prototype/release/site'
for rule in config['headers']:
    rule['headers'] = [h for h in rule['headers'] if h['key'].lower() != 'x-robots-tag']
(RELEASE / 'vercel.production.json').write_text(json.dumps(config, indent=2) + '\n')
print(f'Prepared {len(pages) - 1} indexable pages at {SITE}. Preview is still noindex. Nothing deployed.')
